"""Extract Experiment C fixed-plan lifecycle counts and emit Table 7A."""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


SCRIPT_PATH = Path(__file__).resolve()
REPO_ROOT = SCRIPT_PATH.parents[3]
FIGURES_ROOT = SCRIPT_PATH.parents[1]
TABLE_NAME = "tab_pd_lifecycle_invariants"

DEFAULT_REPORT = REPO_ROOT / "evaluation/data/processed/REPORT.md"
DEFAULT_CSV = FIGURES_ROOT / "data" / f"{TABLE_NAME}.csv"
DEFAULT_TEX = FIGURES_ROOT / "tables" / f"{TABLE_NAME}.tex"

EXPECTED_EVENTS = (
    "Parent switch calls",
    "PDE writes",
    "TLB batches",
    "Vidmem allocations during switch",
    "Vidmem free/evictions during switch",
    "Copy pushes during switch",
    "Faults",
)
CSV_COLUMNS = (
    "event",
    "count",
    "interpretation",
    "source_section",
    "validity",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    parser.add_argument("--tex", type=Path, default=DEFAULT_TEX)
    return parser.parse_args()


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def split_markdown_row(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def extract_section(report: str) -> str:
    start_heading = "### 6.1 固定 Plan 下的 P/D 循环"
    end_heading = "### 6.2 Plan Class 扩缩容守恒"
    start = report.find(start_heading)
    end = report.find(end_heading, start + len(start_heading))
    require(start >= 0 and end > start, "Experiment C §6.1 not found")
    return report[start:end]


def build_data(report_path: Path) -> pd.DataFrame:
    report = report_path.read_text(encoding="utf-8")
    section = extract_section(report)
    require("1,000 个 P/D 循环产生" in section, "cycle count statement differs")
    require("没有进入物理页分配、释放、数据复制或缺页迁移路径" in section,
            "fixed-plan lifecycle conclusion differs")

    lines = section.splitlines()
    header = ["计数", "结果"]
    start = next(
        (index for index, line in enumerate(lines) if split_markdown_row(line) == header),
        -1,
    )
    require(start >= 0, "§6.1 event table not found")
    table_lines: list[str] = []
    for line in lines[start:]:
        if not line.startswith("|"):
            break
        table_lines.append(line)
    require(len(table_lines) == len(EXPECTED_EVENTS) + 2, "§6.1 row count differs")

    records: list[dict[str, object]] = []
    for row_index, line in enumerate(table_lines[2:]):
        cells = split_markdown_row(line)
        require(len(cells) == 2, f"malformed §6.1 row: {line}")
        event, raw_count = cells
        require(event == EXPECTED_EVENTS[row_index], f"unexpected event order: {event}")
        count = int(raw_count.replace(",", ""))
        require(count >= 0, f"negative count for {event}")
        records.append(
            {
                "event": event,
                "count": count,
                "interpretation": (
                    "mapping-control operations"
                    if row_index < 3
                    else "no allocation/migration/fault activity"
                ),
                "source_section": "REPORT.md Experiment C §6.1",
                "validity": "valid_driver_event_count",
            }
        )

    data = pd.DataFrame.from_records(records, columns=CSV_COLUMNS)
    require(data["count"].tolist()[:3] == [2000, 8000, 2000],
            "mapping-control counts differ")
    require((data["count"].iloc[3:] == 0).all(), "lifecycle-invariant count is nonzero")
    return data


def write_csv(data: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    data.to_csv(path, index=False)
    serialized = pd.read_csv(path)
    require(list(serialized.columns) == list(CSV_COLUMNS), "CSV columns differ")
    require(len(serialized) == len(EXPECTED_EVENTS), "serialized row count differs")


def latex_escape(text: str) -> str:
    replacements = {
        "&": r"\&",
        "%": r"\%",
        "_": r"\_",
        "#": r"\#",
    }
    return "".join(replacements.get(character, character) for character in text)


def write_table(data: pd.DataFrame, path: Path) -> None:
    rows = []
    for row in data.itertuples(index=False):
        rows.append(
            f"{latex_escape(row.event)} & {int(row.count):,} & "
            f"{latex_escape(row.interpretation)} \\\\"
        )

    latex = "\n".join(
        [
            "% Generated by figures/scripts/tab_pd_lifecycle_invariants.py.",
            r"\begin{table*}[t]",
            r"  \centering",
            (
                r"  \caption{Driver events observed over 1,000 bidirectional P/D "
                r"switching cycles. One cycle contains one P$\rightarrow$D and one "
                r"D$\rightarrow$P transition, producing 2,000 parent switches. "
                r"Within a fixed plan, P/D switching does not allocate, free, or copy "
                r"physical backing. This result is not a complete conservation proof "
                r"for Plan Class resizing.}"
            ),
            r"  \label{tab:pd-lifecycle-invariants}",
            r"  \small",
            r"  \begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrl@{}}",
            r"    \toprule",
            r"    Event & Count & Interpretation \\",
            r"    \midrule",
            *[f"    {row}" for row in rows],
            r"    \bottomrule",
            r"  \end{tabular*}",
            r"\end{table*}",
            "",
        ]
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(latex, encoding="utf-8")


def main() -> None:
    args = parse_args()
    data = build_data(args.report)
    write_csv(data, args.csv)
    write_table(data, args.tex)
    print(f"Wrote {args.csv}")
    print(f"Wrote {args.tex}")
    print("Verified: 2,000 parent switches over 1,000 bidirectional cycles; "
          "all allocation/migration/fault counters are zero.")


if __name__ == "__main__":
    main()
